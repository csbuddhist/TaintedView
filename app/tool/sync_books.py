#!/usr/bin/env python3
"""把 books/ 书稿打包成 App 资源，并刷新 pubspec.yaml 里的 assets 清单。

用法（在仓库根目录或 app/ 下运行均可）:
    python3 app/tool/sync_books.py

输出:
    app/assets/data/catalog.json                 书目（path 为 books/<bookId>）
    app/assets/data/books/<bookId>/book.json     书籍元数据与目录
    app/assets/data/books/<bookId>/chapters/     章节段落块
    app/assets/data/books/<bookId>/images/       图片

Flutter 的 assets 只能按目录逐个声明（不递归），所以每次同步后重写
pubspec.yaml 中 BEGIN/END 标记之间的目录清单。
"""

from __future__ import annotations

import shutil
import subprocess
import sys
from pathlib import Path

APP = Path(__file__).resolve().parent.parent
ROOT = APP.parent
DATA = APP / "assets" / "data"
PUBSPEC = APP / "pubspec.yaml"
BEGIN = "    # BEGIN generated by tool/sync_books.py"
END = "    # END generated by tool/sync_books.py"


def main() -> int:
    if DATA.exists():
        shutil.rmtree(DATA)
    subprocess.run([sys.executable, str(ROOT / "tools" / "build_books.py"), "--out", str(DATA)], check=True)
    (DATA / "report.md").unlink(missing_ok=True)

    dirs = sorted({p.parent for p in DATA.rglob("*") if p.is_file()})
    lines = [f"    - {d.relative_to(APP).as_posix()}/" for d in dirs]

    text = PUBSPEC.read_text(encoding="utf-8")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    PUBSPEC.write_text(head + BEGIN + "\n" + "\n".join(lines) + "\n" + END + tail, encoding="utf-8")
    print(f"已写入 {len(lines)} 个资源目录到 {PUBSPEC.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
